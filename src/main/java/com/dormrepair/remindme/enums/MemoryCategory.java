package com.dormrepair.remindme.enums;

// 用户私有记忆分类枚举。标记 private_knowledge 中每条记忆的归属类型，便于后续按分类过滤检索、定向补充
public enum MemoryCategory {

    // ---------- 用户自身信息 ----------

    // 用户自身属性与状态：年级、专业、住址、性别、身高等长期不变或变化缓慢的事实
    PERSONAL_INFO,

    // ---------- 活动/事务 ----------

    // 近期或远期的事务：旅游、会议、实习、搬家、面试等一次性或阶段性事件
    ACTIVITY,

    // ---------- 重要日期/纪念日 ----------

    // 重要日期与纪念日：生日、结婚纪念日、周年、考试日等每年/单次需被记住的关键日期
    EVENT,

    // ---------- 学习相关 ----------

    // 长期目标或计划：如「考研」「减重 10 斤」，需长期跟踪的目标类事项
    PLAN,
    // 考试安排：如「6 月 20 日期末考试」，时间确定、重要程度高的事件
    EXAM_SCHEDULE,

    // ---------- 生活相关 ----------

    // 健康状况：如「对海鲜过敏」「高血压」，用于经期/饮食建议时的风险规避
    HEALTH_CONDITION,
    // 饮食偏好：如「不吃辣」「素食」，用于推荐类工具的参数过滤
    DIET_PREFERENCE,
    // 个人习惯：有固定时间/频率规律的行为，如「每天早上 7 点起床」「睡前看书」
    HABIT,
    // 兴趣爱好：如「喜欢打篮球」「画画」，用于闲聊、活动推荐
    INTEREST,

    // ---------- 系统相关 ----------

    // 语言风格偏好：如「喜欢简洁回答」「语气可爱」，供 LLM 输出风格调节使用
    LANGUAGE_STYLE,

    // ---------- 其他 ----------

    // 兜底分类：以上都不匹配的记忆内容暂放此类，后续可人工/算法再归类
    OTHER
}
