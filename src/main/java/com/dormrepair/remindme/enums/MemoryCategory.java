package com.dormrepair.remindme.enums;

/**
 * 记忆分类枚举
 * <p>
 * 用于标记用户私有记忆的类型，便于后续按分类过滤检索。
 * 分类使用原则详见 rag设计.md 第3.3节。
 * </p>
 */
public enum MemoryCategory {

    // ========== 用户自己的信息 ==========
    /** 用户自己的属性和状态（年级、专业、住址、性别等） */
    PERSONAL_INFO,

    // ========== 活动/事务 ==========
    /** 用户要做或正在做的事情（旅游、会议、实习等） */
    ACTIVITY,

    // ========== 重要日期/纪念日 ==========
    /** 重要日期/纪念日（生日、结婚纪念日等） */
    EVENT,

    // ========== 学习相关 ==========
    /** 固定的课程安排（如"每周三8:00有数学课"） */
    COURSE,
    /** 长期目标或计划（如"考研究生"、"减肥10斤"） */
    PLAN,
    /** 考试安排（如"6月20日期末考试"） */
    EXAM_SCHEDULE,

    // ========== 生活相关 ==========
    /** 日常作息习惯（如"每天早上7点起床"） */
    DAILY_ROUTINE,
    /** 健康状况（如"用户对海鲜过敏"） */
    HEALTH_CONDITION,
    /** 饮食偏好（如"用户不吃辣"） */
    DIET_PREFERENCE,
    /** 个人习惯（如"喜欢睡前看书"） */
    HABIT,
    /** 兴趣爱好（如"喜欢打篮球"） */
    INTEREST,

    // ========== 系统相关 ==========
    /** 语言风格偏好（如"用户喜欢简洁回答"） */
    LANGUAGE_STYLE,

    // ========== 其他 ==========
    /** 兜底：以上都不属于的 */
    OTHER
}
